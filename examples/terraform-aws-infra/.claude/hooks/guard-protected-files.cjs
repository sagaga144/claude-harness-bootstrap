#!/usr/bin/env node
// PreToolUse: Edit|Write. Blocks hand edits to state, plans, lockfiles, provider cache
// and .env files. Override: start the session with ALLOW_PROTECTED_EDIT=1.
// Exit 0 = allow, 2 = block. Fails open on its own errors.
"use strict";
const PROTECTED = [
  [/\.tfstate(?:\.backup)?$/i, "Terraform state is managed by Terraform, never by hand"],
  [/\.tfplan$/i, "saved plans are generated by `infra plan`"],
  [/(?:^|[\\/])\.terraform\.lock\.hcl$/i, "update provider locks with `terraform init -upgrade`"],
  [/(?:^|[\\/])\.terraform[\\/]/i, ".terraform/ is a generated cache"],
  [/(?:^|[\\/])uv\.lock$/i, "update with `uv lock` / `uv add`"],
  [/(?:^|[\\/])\.env(?:\.(?!example$)[\w.-]+)?$/i, ".env files hold secrets"],
];
try {
  if (process.env.ALLOW_PROTECTED_EDIT === "1") process.exit(0);
  const input = JSON.parse(require("fs").readFileSync(0, "utf8") || "{}");
  const p = String((input.tool_input && input.tool_input.file_path) || "");
  const hit = PROTECTED.find(([re]) => re.test(p));
  if (hit) {
    console.error(`Blocked edit to ${p}: ${hit[1]}. Override with ALLOW_PROTECTED_EDIT=1 if the user asks for it.`);
    process.exit(2);
  }
  process.exit(0);
} catch {
  process.exit(0);
}
